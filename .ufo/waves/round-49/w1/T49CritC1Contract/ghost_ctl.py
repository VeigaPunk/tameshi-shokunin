#!/usr/bin/env python3
"""T49CritC1Contract probe: CTL_G, a no-read control cheaper than CTL_K/CTL_K2.

Builds a throwaway fixture repo (mktemp under the seat scratch), replaces the seven
target section bodies with NULL citations (path pointers to files that do not exist),
keys seven ledger entries with a stable non-record input, writes `absent` read rows
with no excerpt, and scores with the frozen round-49 C1 counter. Probe only.
"""
import hashlib
import importlib.util
import json
import os
import shutil
import subprocess
import sys

S = sys.argv[1]
LANE = '/home/vgpnk/Projects/shokunin/tameshi-shokunin'
BASE = '8ca67421111fa354b47b803358391d0b07fc6db9'
ENV = {k: v for k, v in os.environ.items() if not k.startswith('GIT_')}
ENV.update(GIT_CONFIG_GLOBAL='/dev/null', GIT_CONFIG_NOSYSTEM='1',
           GIT_AUTHOR_NAME='r49-probe', GIT_AUTHOR_EMAIL='probe@invalid',
           GIT_COMMITTER_NAME='r49-probe', GIT_COMMITTER_EMAIL='probe@invalid',
           PYTHONDONTWRITEBYTECODE='1')


def git(repo, *a, data=None):
    r = subprocess.run(['git', '-C', repo] + list(a), input=data, capture_output=True, env=ENV)
    if r.returncode != 0:
        raise SystemExit('git %s failed: %s' % (' '.join(a), r.stderr.decode()[-300:]))
    return r.stdout.decode()


spec = importlib.util.spec_from_file_location('c1', os.path.join(LANE, '.ufo/evidence/round-49/c1/measure.py'))
c1 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(c1)
TARGETS, FLOORS = c1.TARGETS, c1.FLOORS

D = os.path.join(S, 'fix')
shutil.rmtree(D, ignore_errors=True)
git(S, 'clone', '--quiet', '--shared', LANE, D)
top = git(D, 'rev-parse', '--show-toplevel').strip()
assert os.path.realpath(top) == os.path.realpath(D), (top, D)
git(D, 'reset', '--hard', '-q', BASE)
git(D, 'clean', '-qfd')
print('FIXTURE', D, 'toplevel-ok', git(D, 'rev-parse', 'HEAD').strip()[:12])

skill = open(os.path.join(D, 'SKILL.md'), 'rb').read()
lines = skill.decode('utf-8', 'surrogateescape').split('\n')
if lines and lines[-1] == '':
    lines.pop()
secs = {s['heading']: s for s in c1.load_monitor_module(LANE).sectionize(skill) if s['heading'] in TARGETS}
assert len(secs) == 7, len(secs)

# Rewrite each target body with FLOORS[h] ghost path pointers; heading text untouched.
repl = {}
for i, h in enumerate(TARGETS):
    n = FLOORS[h]
    body = ['', 'Ghost citations, generated by the control driver:']
    toks = ['ghost-%d-%02d.md' % (i, j) for j in range(n)]
    for k in range(0, len(toks), 6):
        body.append(' '.join('`%s`' % t for t in toks[k:k + 6]))
    repl[h] = body
for h in sorted(TARGETS, key=lambda x: secs[x]['start'], reverse=True):
    s = secs[h]
    lines[s['start'] - 1:s['end']] = [h] + repl[h]
new_skill = '\n'.join(lines) + '\n'
open(os.path.join(D, 'SKILL.md'), 'w', encoding='utf-8', errors='surrogateescape').write(new_skill)

# Ledger: seven entries keyed to the new section shas; input = one stable non-record blob.
new_secs = {s['heading']: s for s in c1.load_monitor_module(LANE).sectionize(
    new_skill.encode('utf-8', 'surrogateescape')) if s['heading'] in TARGETS}
assert len(new_secs) == 7
stable = 'corpus/knowledge/operator-runbook.md'
sha_stable = hashlib.sha256(git(D, 'cat-file', 'blob', BASE + ':' + stable).encode('utf-8', 'surrogateescape')
                           if False else subprocess.run(['git', '-C', D, 'cat-file', 'blob', BASE + ':' + stable],
                                                        capture_output=True, env=ENV).stdout).hexdigest()
trace_path = '.ufo/evidence/round-49/c1/ghost-trace.json'
os.makedirs(os.path.join(D, os.path.dirname(trace_path)), exist_ok=True)
open(os.path.join(D, trace_path), 'w').write(json.dumps(
    {'schema': 'tameshi-trace-inputs-v1', 'inputs': {}}, indent=1) + '\n')
ledger_path = os.path.join(D, '.ufo/evidence/round-21/coldread/ledger.json')
led = json.load(open(ledger_path))
whole = hashlib.sha256(new_skill.encode('utf-8', 'surrogateescape')).hexdigest()
for h in TARGETS:
    led['entries'].append({
        'skill_sha256': whole, 'start': new_secs[h]['start'], 'end': new_secs[h]['end'],
        'heading': h, 'sha256': new_secs[h]['sha256'], 'class': 'instruction',
        'verdict': 'executed-ok', 'blocking_gaps': 0, 'wrong_expectations': 0,
        'minor_gaps': 0, 'commands_executed_count': 1,
        'inputs': {stable: sha_stable}, 'traces': [trace_path],
    })
json.dump(led, open(ledger_path, 'w'), indent=1, ensure_ascii=False)
git(D, 'add', '-A')
git(D, 'commit', '-q', '-m', 'CTL_G: ghost-pointer bodies + entries')
rev1 = git(D, 'rev-parse', 'HEAD').strip()
print('REV_CONTENT', rev1)

# Read rows: every pointer the counter now finds, answered `absent` with no excerpt.
ptrs, missing = c1.list_pointers(D, rev1)
assert not missing, missing
rows = [{'heading': p['heading'], 'ordinal': p['ordinal'], 'raw': p['raw'], 'file': None,
         'ranges': None, 'verdict': 'absent', 'excerpt': ''} for p in ptrs]
kinds = {}
for p in ptrs:
    kinds[p['pointer_kind']] = kinds.get(p['pointer_kind'], 0) + 1
print('POINTERS', len(ptrs), kinds, 'unresolved-before-reads', sum(1 for p in ptrs if p['file'] is None))
reads = os.path.join(D, '.ufo/evidence/round-49/c1/reads.json')
json.dump({'schema': 'tameshi-r49-reads-v1', 'rows': rows}, open(reads, 'w'), indent=1)
git(D, 'add', '-A')
git(D, 'commit', '-q', '-m', 'CTL_G: absent read rows')
rev = git(D, 'rev-parse', 'HEAD').strip()
print('REV', rev)
w = os.path.join(S, 'w-ghost')
shutil.rmtree(w, ignore_errors=True)
os.makedirs(w)
r = subprocess.run([sys.executable, '-B', os.path.join(LANE, '.ufo/evidence/round-49/c1/measure.py'),
                    '--lane', D, '--rev', rev, '--work', w],
                   capture_output=True, env=dict(ENV, TMPDIR=S))
out = r.stdout.decode()
open(os.path.join(S, 'ctl-g.stdout'), 'w').write(out + r.stderr.decode())
for line in out.splitlines():
    if line.startswith('C1_R49:') or line.startswith('SECTION') or line.startswith('UNCOVERED'):
        print(line)
print('EXIT', r.returncode)
print('STDERR', r.stderr.decode()[-400:])
