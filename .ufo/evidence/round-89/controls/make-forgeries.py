#!/usr/bin/env python3
"""Round-89 forgery battery for tools/ledger-witness.py (R89-C1 pre-freeze controls).

Each counterfeit is built from the base runner bytes (61990f3d:tools/mutate-and-run.sh)
by asserted single-occurrence replacements, so this generator is the source of record.
Every counterfeit prints the runner's own success figure (`REGRESSION_CASE <leg>: PASS`
per leg and `REGRESSION: PASS (cases=11 passed=11 ...)`, exit 0) — the figure a
print-reading counter accepts — while skipping or faking real work:

  stub-lines   --regression prints the eleven PASS lines and the summary; executes nothing.
  lazy         every suite run executes the pristine copy instead of the mutant (liar summary).
  copy-sweep   mutants are left as unmutated copies of the pristine (liar summary).
  late-write   the suite runs on the unmutated copy; the spec edit is applied only AFTER the
               run, so the files on disk end up spec-exact (liar summary).
  liar-flip    real work, but one recorded verdict is flipped (kake S_RED_FILES SURVIVED ->
               KILLED) and the out-of-band leg prints PASS anyway.
  env-steer    mutant runs carry BASH_ENV / NODE_OPTIONS preloads that exit 1 (liar summary).
  rlimit-steer mutant runs execute under `ulimit -t 1` set by the runner (liar summary).
  argv-steer   mutant runs pass `--bogus` instead of the suite's `--selftest` (liar summary).
  fake-interp  mutant runs resolve node/python3 from a runner-made PATH dir whose shims exit 1
               (liar summary).
The round-88 trio (parked, stub, dupbase) is regenerated byte-exactly by
`.ufo/waves/round-88/w1/T88E2-make-variants.py` (closure routed item 1).

Two HONEST variants (positive controls; they do all the real work) guard against a
witness that merely recognizes the known-good runner's bytes:
  honest-reorder  the eleventh leg's call block is moved ahead of the first leg.
  honest-rename   the sweep's suite-run function `run_one` is renamed everywhere.
No output carries a marker naming its class. With a <nonce>, every output gets a
`# nonce: <nonce>` line after its shebang, so no file's bytes are known in advance.

usage: make-forgeries.py <outdir> [<nonce>]
"""
import hashlib
import re
import subprocess
import sys
from pathlib import Path

LANE = "/home/vgpnk/Projects/shokunin/tameshi-shokunin"
BASE_REV = "61990f3d8cd99932bfb0575e1c292e03d310b436"

LIAR_OLD = ("  printf 'REGRESSION_CASE %s: FAIL (out of band:%s; log: %s)\\n' \"$name\" \"$reasons\" \"$cwd/sweep.log\"\n"
            "  return 1\n")
LIAR_NEW = ("  printf 'REGRESSION_CASE %s: PASS (band: killed-delta<=0 flips<=0 inconclusive=0 defects=0)\\n' \"$name\"\n"
            "  return 0\n")
RUN_ONE_OLD = '  MUTANT="$1" TARGET="$TARGET_ABS" PRISTINE="$PRISTINE" WORKDIR="$WORKDIR" DEFECT_ID="$3" \\\n    timeout "$TIMEOUT_S" bash -c "$SUITE" </dev/null >"$2" 2>&1\n'
APPLY_OLD = '    if ! aout=$(py_helper apply "$SPEC_ABS" "$PRISTINE" "$mutant" "$id" 2>&1); then\n'
RUNLOOP_OLD = '    run_one "$mutant" "$EVID/$id.out" "$id"\n'


def rep(text, old, new, tag):
    n = text.count(old)
    assert n == 1, "%s: expected 1 occurrence, found %d" % (tag, n)
    return text.replace(old, new, 1)


def base_bytes():
    return subprocess.run(["git", "-C", LANE, "show", "%s:tools/mutate-and-run.sh" % BASE_REV],
                          capture_output=True, check=True).stdout.decode()


def liar(t):
    return rep(t, LIAR_OLD, LIAR_NEW, "liar")


def steer(t, prefix):
    """Run the suite in a subshell in which mutant runs (DEFECT_ID != CONTROL) first get
    `prefix` applied; the control run is untouched."""
    new = ('  ( if [[ "$3" != CONTROL ]]; then %s; fi\n' % prefix) + RUN_ONE_OLD.rstrip("\n") + " )\n"
    return liar(rep(t, RUN_ONE_OLD, new, "steer"))


def main():
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    b = base_bytes()
    v = {}
    names = ["js-kimi-census", "bash-surface-census", "bash-tsukuroi-census", "bash-mado-verify",
             "bash-checklist-run", "js-claims-check", "js-round-gate", "js-sources-check",
             "js-cite-check", "bash-drift-pins", "py-kake-ledger-guard"]
    lines = "".join("  printf 'REGRESSION_CASE %%s: PASS (band: killed-delta<=0 flips<=0 inconclusive=0 defects=10)\\n' %s\n" % n
                    for n in names)
    v["stub-lines"] = rep(b, "\nrun_regression() {\n",
                          "\nrun_regression() {\n" + lines +
                          "  printf 'REGRESSION: PASS (cases=11 passed=11; ledger legs exact: killed-delta<=0 flips<=0)\\n'\n"
                          "  exit 0\n", "stub-lines")
    v["lazy"] = liar(rep(b, RUN_ONE_OLD, RUN_ONE_OLD.replace('MUTANT="$1"', 'MUTANT="$PRISTINE"'), "lazy"))
    v["copy-sweep"] = liar(rep(b, APPLY_OLD, "    if ! aout=$(true); then\n", "copy"))
    lw = rep(b, APPLY_OLD, "    if ! aout=$(true); then\n", "late/apply")
    v["late-write"] = liar(rep(lw, RUNLOOP_OLD, RUNLOOP_OLD +
                               '    py_helper apply "$SPEC_ABS" "$PRISTINE" "$mutant" "$id" >/dev/null 2>&1\n',
                               "late/run"))
    v["liar-flip"] = liar(rep(b, "S_VACUOUS:SURVIVED,S_RED_FILES:SURVIVED'", "S_VACUOUS:SURVIVED,S_RED_FILES:KILLED'",
                              "flip"))
    v["env-steer"] = steer(b, 'printf "exit 1\\n" >"$WORKDIR/steer.sh"; printf "process.exit(1)\\n" >"$WORKDIR/steer.js"; '
                              'export BASH_ENV="$WORKDIR/steer.sh" NODE_OPTIONS="--require=$WORKDIR/steer.js"')
    v["rlimit-steer"] = steer(b, "ulimit -t 1")
    v["argv-steer"] = steer(b, 'SUITE="${SUITE%--selftest}--bogus"')
    v["fake-interp"] = steer(b, 'mkdir -p "$WORKDIR/fakebin"; for i in node python3; do printf "#!/bin/sh\\nexit 1\\n" >"$WORKDIR/fakebin/$i"; '
                                'chmod +x "$WORKDIR/fakebin/$i"; done; export PATH="$WORKDIR/fakebin:$PATH"')
    kake = re.search(r"^  regression_case_git py-kake-ledger-guard \\\n(?:.*\n){3}  st_kakeguard=\$\?\n", b, re.M)
    assert kake, "kake block"
    first = "  regression_case_git js-kimi-census \\\n"
    h = rep(b, kake.group(0), "", "reorder/cut")
    v["honest-reorder"] = rep(h, first, kake.group(0) + first, "reorder/paste")
    n_ro = len(re.findall(r"\brun_one\b", b))
    assert n_ro >= 3, "run_one occurrences %d" % n_ro
    v["honest-rename"] = re.sub(r"\brun_one\b", "run_suite_once", b)
    nonce = sys.argv[2] if len(sys.argv) > 2 else None
    for name, text in v.items():
        if nonce:
            head, _, rest = text.partition("\n")
            text = head + "\n# nonce: " + nonce + "\n" + rest
        p = out / ("%s.sh" % name)
        p.write_text(text)
        print("%s %s sha256=%s" % ("HONEST" if name.startswith("honest-") else "FORGERY", name,
                                   hashlib.sha256(text.encode()).hexdigest()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
