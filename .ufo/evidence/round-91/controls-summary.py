#!/usr/bin/env python3
"""Round-91 control-summary generator (QUALITY 147, first half).

Reads every control receipt under pre-freeze/controls/*.out and the pre-registered
expectations in pre-freeze/expected.tsv, and writes pre-freeze/controls/C1-summary.txt
from those bytes — the summary is never hand-authored. Each row states the label the
receipt actually printed, its exit, and the conjunct(s) that made it false.

Usage: python3 -I controls-summary.py --root <lane>   (defaults to the script's lane)
"""
import argparse, glob, os, re

REFUSED_BY = {
    "CTL1-nowork-base": "setup refusal: spec path absent at the base rev",
    "CTL1b-nowork-A": "source=false (the expectations rev has no S318 row and no note amendment)",
    "CTL14-pos": "none — the positive control (honest note generated from the derived table)",
    "CTL2-flip": "mismatched0=false (one verdict flipped)",
    "CTL3-figure": "figure=false (headline k/n inflated)",
    "CTL4-ids": "ids=false (one row deleted)",
    "CTL5-spec": "spec=false (spec bytes unpinned)",
    "CTL6-noop": "invalid0=false (new == old)",
    "CTL7-syntax": "invalid0=false (bash -n fails) and trivial0=false",
    "CTL8-absent": "invalid0=false (old string absent) and figure=false",
    "CTL9-equiv": "witnessed=false (a survivor's witness is identical)",
    "CTL10-source": "source=false (cited S-id absent from SOURCES.md)",
    "CTL11-trivial": "trivial0=false (mutant dies on a clean registry)",
    "CTL12-pin": "pin=false (gate sha256 mismatch)",
    "CTL15-coverage": "coverage=false (README row naming the note removed)",
    "CTL16-oldsource": "source=false (note cites S315, at or below the base maximum)",
    "VOV1-dup-row": "ids=false (a duplicate C02 row)",
    "VOV3-draft-column": "ids=false (a draft column whose verdict cell is out of vocabulary)",
    "V4-replace": "setup refusal: replace-refs-present (a local git replace ref)",
    "C2-nowork-base": "rows=fail (no r91 manifest sections at the base)",
    "C2-nowork-instr": "rows=fail (manifest present, repairs absent)",
    "C2-pos": "none — the positive control",
    "C2-wrongcount": "rows=fail (a marker whose operative sentence states a false count)",
    "C2-keepred": "rows=fail (a marker without the operative sentence)",
}
ORDER = ["CTL1-nowork-base", "CTL1b-nowork-A", "CTL14-pos", "CTL2-flip", "CTL3-figure", "CTL4-ids",
         "CTL5-spec", "CTL6-noop", "CTL7-syntax", "CTL8-absent", "CTL9-equiv", "CTL10-source",
         "CTL11-trivial", "CTL12-pin", "CTL15-coverage", "CTL16-oldsource", "VOV1-dup-row",
         "VOV3-draft-column", "V4-replace", "C2-nowork-base", "C2-nowork-instr", "C2-pos",
         "C2-wrongcount", "C2-keepred"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    a = ap.parse_args()
    d = os.path.join(a.root, ".ufo/evidence/round-91/pre-freeze/controls")
    rows = []
    for name in ORDER:
        p = os.path.join(d, name + ".out")
        if not os.path.exists(p):
            rows.append((name, "MISSING", "-", "receipt absent"))
            continue
        t = open(p, encoding="utf-8", errors="replace").read()
        m = re.search(r"^(C1_R91_PASS|C2_R91_PASS)=(true|false)$", t, re.M)
        label = (m.group(1) + "=" + m.group(2)) if m else "setup-refusal"
        e = re.search(r"^exit=(\d)$", t, re.M)
        exit_ = e.group(1) if e else "?"
        setup = re.search(r"^C1_SETUP (.+)$", t, re.M)
        if setup:
            label = "C1_SETUP " + setup.group(1).strip()
        rows.append((name, label, exit_, REFUSED_BY.get(name, "-")))
    with open(os.path.join(d, "C1-summary.txt"), "w", encoding="utf-8") as f:
        f.write("# round-91 pre-freeze control summary — GENERATED by .ufo/evidence/round-91/controls-summary.py\n")
        f.write("# from the .out receipts beside it (QUALITY 147: no hand-authored summary)\n")
        f.write("control\tlabel\texit\trefused-by\n")
        for r in rows:
            f.write("\t".join(r) + "\n")
    print("summary rows=%d" % len(rows))
    bad = [r for r in rows if r[1] == "MISSING"]
    print("missing=%d" % len(bad))


if __name__ == "__main__":
    main()
